import { IconClose } from "./Icons";
import { Modal } from "./Modal";

export function HelpOverlay({ onClose }: { onClose: () => void }) {
  return (
    <Modal label="操作指引" onClose={onClose}>
      <div className="help-card" onClick={(e) => e.stopPropagation()}>
        <div style={{ display: "flex", alignItems: "center" }}>
          <h2>操作指引</h2>
          <button className="icon-btn" aria-label="关闭操作指引" style={{ marginLeft: "auto" }} onClick={onClose}>
            <IconClose size={14} />
          </button>
        </div>

        <h3>手部手势</h3>
        <dl>
          <dt>开始绘制</dt>
          <dd>点击工作区的「开始绘制」。指向网格，拇指碰食指起笔，保持指尖相碰移动，分开就收笔。也可以按住鼠标左键画线。</dd>
          <dt>食指轻点按钮</dt>
          <dd>用食指指向按钮，等光标旁出现「弯一下食指」。保持手掌不动，轻弯食指，再伸直点击。也可以用拇指和食指捏合点击。</dd>
          <dt>捏合（拇指+食指）</dt>
          <dd>拾取对象拖拽移动；在「绘制」工具下即落笔；在「雕刻」工具下即按压/拉伸</dd>
          <dt>张开手掌（旋转与缩放）</dt>
          <dd>单手张掌按手部移动幅度线性转动视角；双掌张开可开合缩放，两手同向移动时平移视角（也可随时用鼠标右键拖动旋转、滚轮缩放）。</dd>
          <dt>松开捏合</dt>
          <dd>结束当前操作。绘制时靠近起点并松手可闭合轮廓，捏住旁边的厚度手柄上下拖动可生成实体。</dd>
          <dt>握拳与剪刀手</dt>
          <dd>空闲时握拳片刻打开工具，松拳后用食指轻点或捏合选择。剪刀手停一下再向左或向右划，可撤销或重做。</dd>
          <dt>三指聚焦（食指、中指、无名指）</dt>
          <dd>收起拇指和小指，保持约半秒。视角聚焦选中对象；没有选中时框住全部对象。</dd>
          <dt>五指状态</dt>
          <dd>左上角「当前工具：选择对象」指的是在画布中选模型。「五指识别」是只读状态，不需要点选手指。小指参与区分张掌、握拳和三指聚焦，目前没有单指命令。</dd>
          <dt>双手同时捏合</dt>
          <dd>选中对象后，双手间距控制缩放，双手连线角度控制绕 Y 旋转</dd>
          <dt>食指指向</dt>
          <dd>指针始终跟随食指尖，三维光标会钉在射线命中的表面或绘制平面上</dd>
          <dt>校准</dt>
          <dd>点摄像头面板「校准」，按向导依次在四角保持食指，再完成九点复测。更换设备或镜像设置后需要重新校准</dd>
        </dl>

        <h3>鼠标操作</h3>
        <dl>
          <dt>左键按下</dt>
          <dd>等同于捏合</dd>
          <dt>右键拖动 / 滚轮</dt>
          <dd>旋转视角 / 缩放视角</dd>
          <dt>1 2 3 4</dt>
          <dd>切换 选择 / 绘制 / 雕刻 / 生成</dd>
          <dt>Delete · Esc · Ctrl+Z / Ctrl+Shift+Z</dt>
          <dd>删除选中 / 取消当前操作并回滚 / 撤销与重做场景修改</dd>
          <dt>Ctrl+S · 项目菜单</dt>
          <dd>保存到此浏览器；下载原生项目文件可连同模型资产一起备份、迁移</dd>
          <dt>Ctrl / Shift + 点击对象列表 · Ctrl+A</dt>
          <dd>多选 / 全选；检查器可整体变换、改材质或确认批量删除。画布的「视图」入口可选标准视图和投影方式。</dd>
          <dt>场景指令与局部编辑</dt>
          <dd>支持「把它缩小10%」「把刚才那个改为蓝色」「解释场景」等本地规则；指定区域形变使用对象局部坐标。修改先比较预览，确认后写入，可撤销</dd>
          <dt>空格</dt>
          <dd>暂停或恢复手部输入（用于临时改用鼠标）</dd>
        </dl>

        <h3>推荐工作流</h3>
        <dl>
          <dt>第一步</dt>
          <dd>「绘制」：选择当前工作平面，捏合或按住鼠标画出轮廓，释放后生成独立笔迹。当前绘制基于软件工作平面</dd>
          <dt>第二步</dt>
          <dd>「AI 生成」：在下方输入描述或点击麦克风听写普通话，检查文字后提交。也可在输入框内按 Win + H 使用 Windows 语音键入。</dd>
          <dt>第三步</dt>
          <dd>先预览生成结果，确认后再写入场景。替换只影响绑定的目标版本；拒绝结果保留当前作品</dd>
          <dt>第四步</dt>
          <dd>「雕刻」：接触确认后按压或拉伸；虚拟强度是软件推算值。追踪长时间中断或按 Esc 时回滚</dd>
          <dt>第五步</dt>
          <dd>在检查器建立零件与固定、铰接或滑动连接；关节可设置限位。项目菜单可保存命名版本、比较差异并恢复。GLB、OBJ、STL 支持范围导出，工程关系用原生文件保存</dd>
        </dl>
      </div>
    </Modal>
  );
}
